/**
 * The reviewed allowlist of database objects the `anon` role can reach.
 *
 * WHAT THIS IS
 *   A committed record of exactly what the public anon key can touch in the
 *   `public` schema of the planner-app project (`hufxwovthhsjmtifvign`), as
 *   reviewed by a human. Every entry below was read from the live catalogue on
 *   4 September 2026, checked against what the app actually needs, and kept
 *   deliberately.
 *
 *   `supabase/__tests__/anon-access.test.js` reads the live catalogue and fails
 *   when the database grants anon anything this file does not list, or grants
 *   more on a listed object than this file allows. It skips with an explanation
 *   when no database connection is configured, so it is inert by default and
 *   only speaks when pointed at a real project.
 *
 * WHY IT EXISTS
 *   Anon reach widens on its own here. `pg_default_acl` on this project carries
 *   four entries that hand anon everything on anything new in `public`:
 *
 *     postgres      in public objtype=r   anon=arwdDxt   (every table privilege)
 *     postgres      in public objtype=f   anon=X         (EXECUTE on functions)
 *     postgres      in public objtype=S   anon=rwU       (sequences)
 *     supabase_admin in public            the same three again
 *
 *   Migrations run as `postgres`, so every `create table` and `create function`
 *   picked anon up with nobody having written a grant.
 *
 *   `20260905053043_default_privileges_stop_anon_inheriting.sql` removed the
 *   `postgres` entries' anon grants (and PUBLIC's EXECUTE on functions) on
 *   5 September 2026, so objects created by migrations no longer inherit anon.
 *   The `supabase_admin` entries still grant it and are not ours to change, and
 *   every object created before that date keeps the grant it was born with.
 *   This allowlist is the detection for both.
 *
 *   The same cause has bitten the rest of this workspace. In the Anchor
 *   management app the anon key could read weekly takings, dish cost prices and
 *   customer bookings through owner-rights views. In CashBingo the four
 *   host-only RPCs became anon-callable again on every fresh build. This
 *   repository has its own history of a missing security migration and of
 *   `search_path` drift, so drift here is the expected case, not the unlikely
 *   one.
 *
 *   What this database holds is a single person's whole working life: customer
 *   and contact records, project and task detail, private journal entries, file
 *   attachments and the Microsoft OAuth refresh tokens in `vault_secrets`.
 *
 * WHAT THE CONTROL ACTUALLY IS
 *   RLS, not the grant. Anon holds all seven table privileges on all 21 tables,
 *   because that is what the default privileges give it, and revoking that
 *   project-wide is a change with real blast radius. Every table carries RLS,
 *   and every policy is either scoped to the `authenticated` role or gated on
 *   `auth.uid() = user_id`. This app authenticates with NextAuth, not Supabase
 *   Auth, so `auth.uid()` is NULL for an anon caller and no policy can ever
 *   match.
 *
 *   That was checked rather than assumed. On 4 September 2026 every one of the
 *   21 tables was requested over the REST API with the public anon key from
 *   `.env.local`, and all 21 returned `[]` with HTTP 200. The `why` on each
 *   entry records that reading, not a guess from the policy text.
 *
 *   The value of listing the tables anyway is that a NEW table shows up here as
 *   a failure on the day it is created, while it is still empty and before
 *   anyone has had to think about whether its policies are right.
 *
 * WHAT MUST NEVER APPEAR IN THIS FILE
 *   None of the owner-scoped RPCs, the ownership assertions, the Vault wrappers
 *   or `exec_sql` may ever be added to `ANON_ALLOWLIST`. They are named in
 *   `NEVER_ALLOWLIST` below and the test enforces it, so a careless edit to this
 *   file fails rather than passing quietly. All of them are currently closed to
 *   anon, which is the state to keep. If one of them appears in the live
 *   catalogue, the fix is a migration that revokes it, never an edit here.
 *
 *   Beyond that, no callable function belongs in this file at all. Every
 *   function allowlisted below belongs to the `pg_trgm` extension. The test
 *   also accepts a function named in `TRIGGER_ONLY_FUNCTIONS`, which is empty
 *   since the trigger functions were closed on 5 September 2026, and asserts
 *   nothing else creeps in, so adding a real RPC to the allowlist fails even if
 *   it is not in `NEVER_ALLOWLIST` by name.
 *
 * HOW TO UPDATE IT, DELIBERATELY
 *   1. Do not edit this file to make a failing test pass. A failure means the
 *      live database changed. Find out which migration changed it first.
 *   2. If the new reach is wanted, add the entry with a `why` that says which
 *      feature needs it and which migration granted it, in the same pull request
 *      as that migration.
 *   3. If the new reach is not wanted, write a migration that revokes it. The
 *      shape that actually closes it is both revokes together, because
 *      `create function` grants PUBLIC its own EXECUTE and anon is a member of
 *      PUBLIC:
 *        revoke execute on function public.thing(args) from public, anon;
 *   4. Re-run the test with `SUPABASE_DB_URL` set and paste the result into the
 *      pull request.
 *
 * A NOTE ON POSTGRES VERSIONS
 *   planner-app runs Postgres 15, which has no MAINTAIN privilege, so the
 *   observed default table grant below is seven privileges rather than eight.
 *   The catalogue query still asks for MAINTAIN on a server new enough to have
 *   it. If this project is upgraded to Postgres 17, the default privileges will
 *   hand anon MAINTAIN on all 21 tables and the test will fire once on every
 *   one of them. That is the check working, not a false alarm: somebody should
 *   look, then add MAINTAIN to `SUPABASE_DEFAULT_TABLE_GRANT` in the same pull
 *   request as the upgrade.
 *
 * SCOPE
 *   The `public` schema only, which is where everything this repository creates
 *   lives. `graphql_public.graphql()` is also anon-executable; that is the stock
 *   Supabase GraphQL entry point, it resolves through the same RLS policies, and
 *   it is out of scope here.
 *
 * EVIDENCE
 *   Read from the live catalogue via the Supabase MCP against project
 *   `hufxwovthhsjmtifvign` on 4 September 2026, using `has_table_privilege` and
 *   `has_function_privilege` for the `anon` role, plus the REST API check
 *   described above. No grant was changed and no migration was run.
 */

