/**
 * The catalogue query the test runs against the live database. Read-only.
 *
 * It asks `has_*_privilege` rather than reading ACL arrays, because that is the
 * question worth answering: what anon can actually do, including anything it
 * inherits through PUBLIC. Functions are keyed by identity arguments so an
 * overload cannot hide behind a sibling with the same name.
 *
 * Every `name` is cast to `text` explicitly, and this is load-bearing rather
 * than tidiness. `pg_class.relname` is of type `name`, which is 63 bytes. Union
 * a `name` column with the `text` one the function branch produces and Postgres
 * resolves the whole column to `name`, silently truncating every function
 * signature at 63 characters. Two overloads differing only after character 63
 * then collapse to the same key, which is precisely the hiding this query is
 * meant to prevent. Verified against planner-app on 4 September 2026: without
 * the casts, `gin_extract_query_trgm(text, internal, smallint, internal, inte`
 * is what comes back.
 */
export const ANON_CATALOGUE_QUERY = `
with table_privs as (
  select case when current_setting('server_version_num')::int >= 170000
              then array[${TABLE_PRIVILEGES_PG17.map((p) => `'${p}'`).join(',')}]
              else array[${TABLE_PRIVILEGES.map((p) => `'${p}'`).join(',')}] end as names
),
rel as (
  select case c.relkind when 'r' then 'table' when 'p' then 'table'
                        when 'v' then 'view' when 'm' then 'materialized view' end as kind,
         c.relname::text as name,
         (select coalesce(array_agg(p order by p), array[]::text[])
            from table_privs, unnest(table_privs.names) p
           where has_table_privilege('anon', c.oid, p)) as privileges
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r','p','v','m')
),
seq as (
  select 'sequence' as kind, c.relname::text as name,
         (select coalesce(array_agg(p order by p), array[]::text[])
            from unnest(array[${SEQUENCE_PRIVILEGES.map((p) => `'${p}'`).join(',')}]) p
           where has_sequence_privilege('anon', c.oid, p)) as privileges
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'S'
),
fn as (
  select 'function' as kind,
         (p.proname::text || '(' || pg_get_function_identity_arguments(p.oid) || ')') as name,
         array['EXECUTE'] as privileges
    from pg_proc p
   where p.pronamespace = 'public'::regnamespace
     and has_function_privilege('anon', p.oid, 'EXECUTE')
)
select coalesce(json_agg(row_to_json(x) order by x.kind, x.name), '[]'::json) as reachable
  from (
    select * from rel where cardinality(privileges) > 0
    union all select * from seq where cardinality(privileges) > 0
    union all select * from fn
  ) x;
`.trim();

/**
 * A second read-only query, reported rather than asserted on. Functions without
 * an explicit `search_path` resolve unqualified names against whatever the
 * caller's path happens to be, which matters most for SECURITY DEFINER. This
 * repository has had `search_path` drift before, so the test prints what it
 * finds instead of leaving it invisible.
 *
 * Extension-owned functions are excluded: `pg_trgm` installs 31 C-language
 * functions into `public` with no `search_path`, which is normal and is not this
 * repository's to fix.
 */
export const MISSING_SEARCH_PATH_QUERY = `
select coalesce(json_agg(json_build_object(
         'name', p.proname::text || '(' || pg_get_function_identity_arguments(p.oid) || ')',
         'security', case when p.prosecdef then 'DEFINER' else 'invoker' end
       ) order by p.proname), '[]'::json) as missing
  from pg_proc p
 where p.pronamespace = 'public'::regnamespace
   and p.prokind = 'f'
   and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
   and not exists (select 1 from unnest(coalesce(p.proconfig, array[]::text[])) cfg
                    where cfg like 'search\\_path=%');
`.trim();

